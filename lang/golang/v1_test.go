// v1update is the -v1update flag: write v1's formatted output as the expected
// files of the cases (the files of V1Differences are kept).
var v1update = flag.Bool("v1update", false, "write the v1 generator's formatted output as the expected files of the fixtures")

// TestV1 compares the v1 generator with the expected files of every case: the
// docker image named by SOFT_GEN_V1_IMAGE (masagroup/soft.generator.go:v1.13.1)
// generates the case, its .go files are formatted with gofmt, and every file
// must equal its expected file, but the V1Differences of the case and the
// header line, which names the v1 generator; the manifests are v2 only. It is
// skipped without SOFT_GEN_V1_IMAGE or docker.
func TestV1(t *testing.T) {
	image := os.Getenv("SOFT_GEN_V1_IMAGE")
	if image == "" {
		t.Skip("set SOFT_GEN_V1_IMAGE (masagroup/soft.generator.go:v1.13.1) to compare with the v1 generator")
	}
	if _, err := exec.LookPath("docker"); err != nil {
		t.Skip("docker not found")
	}
	for _, f := range sortedFixtures() {
		t.Run(f.Name, func(t *testing.T) {
			if f.V1Skip != "" {
				t.Skip(f.V1Skip)
			}
			out := t.TempDir()
			runV1(t, image, f, out)
			if *v1update {
				writeV1Expected(t, f, out)
				return
			}
			compareV1(t, f, out)
		})
	}
}

// runV1 generates the case with the v1 image into out and formats the .go files.
func runV1(t *testing.T, image string, f fixture, out string) {
	t.Helper()
	models, _ := filepath.Abs(fixturesDir)
	propsDir, _ := filepath.Abs(filepath.Dir(fixtureProps))
	args := []string{"run", "--rm",
		"-v", models + ":/models", "-v", propsDir + ":/props", "-v", out + ":/out",
		image, "-s", "-m", "/models/" + f.Model, "-o", "/out", "-P", "/props/" + filepath.Base(fixtureProps)}
	for _, entry := range f.EntryPoints {
		args = append(args, "-t", entry)
	}
	keys := make([]string, 0, len(f.Props))
	for key := range f.Props {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		args = append(args, "-p", key+"="+f.Props[key])
	}
	cmd := exec.Command("docker", args...)
	cmd.Env = append(os.Environ(), "MSYS_NO_PATHCONV=1")
	if output, err := cmd.CombinedOutput(); err != nil || bytes.Contains(output, []byte("Exception")) {
		t.Fatalf("v1 generation failed: %v\n%s", err, output)
	}
	files, err := goldentest.ListFiles(out)
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range files {
		full := filepath.Join(out, filepath.FromSlash(file))
		content, err := os.ReadFile(full)
		if err != nil {
			t.Fatal(err)
		}
		content = bytes.ReplaceAll(content, []byte("\r\n"), []byte("\n"))
		content = bytes.Replace(content, []byte(v1Header), []byte(v2Header), 1)
		if strings.HasSuffix(file, ".go") {
			formatted, err := format.Source(content)
			if err != nil {
				t.Errorf("%s: v1 output does not parse: %v", file, err)
				continue
			}
			content = formatted
		}
		if err := os.WriteFile(full, content, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	copyManifests(t, f, out)
}

// The first line of a file generated by v1 and by v2: the only difference
// that every file has, which the comparison ignores.
const (
	v1Header = "// Code generated by soft.generator.go. DO NOT EDIT."
	v2Header = "// Code generated by soft-gen go. DO NOT EDIT."
)

// copyManifests copies the manifests of the expected files into v1's output:
// v1 writes none, and they are compared by TestFixtures only.
func copyManifests(t *testing.T, f fixture, out string) {
	t.Helper()
	expected, err := goldentest.ListFiles(f.expectedDir())
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range expected {
		if path.Base(file) != engine.ManifestName {
			continue
		}
		content, err := os.ReadFile(filepath.Join(f.expectedDir(), filepath.FromSlash(file)))
		if err != nil {
			t.Fatal(err)
		}
		target := filepath.Join(out, filepath.FromSlash(file))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(target, content, 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// compareV1 compares v1's output with the expected files of the case.
func compareV1(t *testing.T, f fixture, out string) {
	t.Helper()
	got, _ := goldentest.ListFiles(out)
	want, _ := goldentest.ListFiles(f.expectedDir())
	gotSet := map[string]bool{}
	for _, file := range got {
		gotSet[file] = true
		if _, deliberate := f.V1Differences[file]; deliberate {
			continue
		}
		v1, _ := os.ReadFile(filepath.Join(out, filepath.FromSlash(file)))
		expected, err := os.ReadFile(filepath.Join(f.expectedDir(), filepath.FromSlash(file)))
		if err != nil {
			t.Errorf("%s: generated by v1 but not expected", file)
			continue
		}
		expected = bytes.ReplaceAll(expected, []byte("\r\n"), []byte("\n"))
		if !bytes.Equal(v1, expected) {
			t.Errorf("%s: v1 differs from the expected file:\n%s", file, writer.UnifiedDiff(file, expected, v1))
		}
	}
	for _, file := range want {
		if _, deliberate := f.V1Differences[file]; !gotSet[file] && !deliberate {
			t.Errorf("%s: expected but not generated by v1", file)
		}
	}
}

// writeV1Expected writes v1's output as the expected files of the case, keeping
// the files of V1Differences.
func writeV1Expected(t *testing.T, f fixture, out string) {
	t.Helper()
	for file := range f.V1Differences {
		content, err := os.ReadFile(filepath.Join(f.expectedDir(), filepath.FromSlash(file)))
		if err != nil {
			continue
		}
		target := filepath.Join(out, filepath.FromSlash(file))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(target, content, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := goldentest.ReplaceDir(f.expectedDir(), out); err != nil {
		t.Fatal(err)
	}
}
