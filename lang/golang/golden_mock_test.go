// notGeneratedBy lists the files matching the pattern under root whose first
// line does not name the generator, relative to root and slash-separated.
func notGeneratedBy(t *testing.T, root, pattern, generator string) []string {
	t.Helper()
	matches, err := filepath.Glob(filepath.Join(root, filepath.FromSlash(pattern)))
	if err != nil {
		t.Fatal(err)
	}
	var others []string
	for _, path := range matches {
		if !strings.Contains(firstLine(t, path), generator) {
			rel, err := filepath.Rel(root, path)
			if err != nil {
				t.Fatal(err)
			}
			others = append(others, filepath.ToSlash(rel))
		}
	}
	return others
}

// firstLine returns the first line of a file.
func firstLine(t *testing.T, path string) string {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	scanner.Scan()
	return scanner.Text()
}
