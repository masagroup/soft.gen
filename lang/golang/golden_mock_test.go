// The ecore directory mixes the mocks of soft.generator.go with mocks
// generated by mockery, which OnlyGenerated keeps: those are excluded by
// their header.
func TestGoldenMockEcore(t *testing.T) {
	root := goldenRoot(t)
	goldentest.Run(t, goldentest.Case{
		Lang: New(), Model: filepath.Join(modelsDir, "ecore.ecore"), PropFiles: []string{goProps},
		Expected:      root,
		Files:         []string{"ecore/*_mock.go", "ecore/*_mock_test.go"},
		Exclude:       notGeneratedBy(t, root, "ecore/*_mock*.go", "soft.generator.go"),
		OnlyGenerated: true,
	})
}

