// Package goldentest compares the files a language generates for a model with
// the files committed in a downstream repository (the golden files generated
// by the v1 generators).
package goldentest

import (
	"bytes"
	"context"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"

	"github.com/masagroup/soft.gen/v2/engine"
	"github.com/masagroup/soft.gen/v2/writer"
)

// Case is one golden comparison: a generation request and the directory of
// the expected files.
type Case struct {
	// Name names the sub-test.
	Name string
	// Lang is the language to run.
	Lang engine.Language
	// Model is the .ecore file.
	Model string
	// Props, PropFiles and EntryPoints are the -p, -P and -t options.
	Props       map[string]string
	PropFiles   []string
	EntryPoints []string
	// Expected is the directory holding the expected files, laid out as the output directory.
	Expected string
	// Files lists the glob patterns (relative to Expected, slash-separated)
	// of the files to compare; empty means every file. A pattern that matches
	// no generated file fails: a golden file was not generated.
	Files []string
	// Exclude lists the glob patterns of the files to leave out of the comparison.
	Exclude []string
	// OnlyGenerated leaves out the expected files that were not generated by
	// a generator: those whose first line is not a "Code generated" header
	// (the hand-written files of a directory mixing both).
	OnlyGenerated bool
	// MaxDiffLines bounds the diff printed per file (0: 80 lines).
	MaxDiffLines int
}

// Root returns the golden root directory: the SOFT_GEN_GOLDEN_ROOT variable,
// else the default; it skips the test when the directory does not exist.
func Root(t *testing.T, defaultRoot string) string {
	t.Helper()
	root := os.Getenv("SOFT_GEN_GOLDEN_ROOT")
	if root == "" {
		root = defaultRoot
	}
	if _, err := os.Stat(root); err != nil {
		t.Skipf("golden root %s not found (set SOFT_GEN_GOLDEN_ROOT)", root)
	}
	return root
}

// Run generates the case into a temporary directory and compares every
// selected file with its expected content, reporting a unified diff per
// differing file, the generated files that have no expected file and the
// expected files that were not generated.
func Run(t *testing.T, c Case) {
	t.Helper()
	run := func(t *testing.T) {
		t.Helper()
		out := t.TempDir()
		req := engine.Request{
			Lang: c.Lang, ModelPath: c.Model, OutDir: out,
			Props: c.Props, PropFiles: c.PropFiles, EntryPoints: c.EntryPoints,
			Silent: true, Output: io.Discard, ErrOutput: os.Stderr,
		}
		if _, err := engine.Run(context.Background(), req); err != nil {
			t.Fatalf("generation failed: %v", err)
		}
		generated := listFiles(t, out)
		expected := listFiles(t, c.Expected)
		selected := func(file string) bool {
			if !matches(c.Files, file) || (len(c.Exclude) > 0 && matches(c.Exclude, file)) {
				return false
			}
			return !c.OnlyGenerated || isGenerated(filepath.Join(c.Expected, filepath.FromSlash(file)))
		}
		compared := 0
		for _, file := range generated {
			if !selected(file) {
				continue
			}
			compared++
			want, err := os.ReadFile(filepath.Join(c.Expected, filepath.FromSlash(file)))
			if err != nil {
				t.Errorf("%s: generated but not expected", file)
				continue
			}
			got, _ := os.ReadFile(filepath.Join(out, filepath.FromSlash(file)))
			want = bytes.ReplaceAll(want, []byte("\r\n"), []byte("\n"))
			if !bytes.Equal(got, want) {
				t.Errorf("%s differs:\n%s", file, truncate(writer.UnifiedDiff(file, want, got), c.MaxDiffLines))
			}
		}
		generatedSet := map[string]bool{}
		for _, file := range generated {
			generatedSet[file] = true
		}
		for _, file := range expected {
			if selected(file) && !generatedSet[file] {
				t.Errorf("%s: expected but not generated", file)
			}
		}
		if compared == 0 {
			t.Errorf("no generated file matched %v (generated: %v)", c.Files, generated)
		}
	}
	if c.Name != "" {
		t.Run(c.Name, run)
	} else {
		run(t)
	}
}

// isGenerated reports whether the file at path starts with a "Code generated"
// header; a missing file counts as generated so that it is reported.
func isGenerated(path string) bool {
	content, err := os.ReadFile(path)
	if err != nil {
		return true
	}
	first, _, _ := bytes.Cut(content, []byte("\n"))
	return bytes.HasPrefix(first, []byte("// Code generated by "))
}

// listFiles lists the files under root, slash-separated, sorted.
func listFiles(t *testing.T, root string) []string {
	t.Helper()
	var files []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			rel, _ := filepath.Rel(root, p)
			files = append(files, filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		t.Fatalf("listing %s: %v", root, err)
	}
	sort.Strings(files)
	return files
}

// matches reports whether a file matches one of the patterns (all when none).
func matches(patterns []string, file string) bool {
	if len(patterns) == 0 {
		return true
	}
	for _, pattern := range patterns {
		if ok, _ := path.Match(pattern, file); ok {
			return true
		}
	}
	return false
}

// truncate keeps the first lines of a diff.
func truncate(diff string, max int) string {
	if max == 0 {
		max = 80
	}
	lines := strings.SplitAfter(diff, "\n")
	if len(lines) <= max {
		return diff
	}
	return strings.Join(lines[:max], "") + "... (" + strconv.Itoa(len(lines)-max) + " more lines)\n"
}
