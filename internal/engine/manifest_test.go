func TestManifestContent(t *testing.T) {
	content, err := Manifest{Generator: "soft.gen go", Version: "v1.13.1", Package: "http://example.com/m"}.Content()
	require.NoError(t, err)
	assert.Equal(t, "# Code generated by soft.gen go. DO NOT EDIT.\ngenerator: soft.gen go\nversion: v1.13.1\npackage: http://example.com/m\n", string(content))

	content, err = Manifest{Generator: "soft.gen go", Package: "urn:a: b #c"}.Content()
	require.NoError(t, err)
	assert.Equal(t, "# Code generated by soft.gen go. DO NOT EDIT.\ngenerator: soft.gen go\npackage: 'urn:a: b #c'\n", string(content), "no version without one; YAML quoting when needed")
}

func TestRunNoManifest(t *testing.T) {
	dir := t.TempDir()
	req := Request{Lang: fakeLanguage{}, ModelPath: shopModel, OutDir: dir, Silent: true, NoManifest: true}
	report, err := Run(context.Background(), req)
	require.NoError(t, err)
	assert.FileExists(t, filepath.Join(dir, "shop", "Product.txt"))
	assert.NoFileExists(t, filepath.Join(dir, "shop", ManifestName))
	for _, file := range report.Files {
		assert.NotEqual(t, ManifestName, path.Base(file.Path), "the report lists no manifest")
	}

	req.NoManifest = false
	_, err = Run(context.Background(), req)
	require.NoError(t, err)
	assert.FileExists(t, filepath.Join(dir, "shop", ManifestName), "the manifest is written by default")
}

