// fakeLanguage generates one file per class of the model: its name and the
// property "greeting", with a user code region.
type fakeLanguage struct{}

func (fakeLanguage) Name() string             { return "fake" }
func (fakeLanguage) AnnotationSource() string { return "http://net.masagroup/soft/2019/GenGo" }
func (fakeLanguage) Properties() []props.Decl {
	return []props.Decl{{Name: "greeting", Default: "hello", Doc: "the greeting", Scope: props.ScopePackage}}
}
func (l fakeLanguage) EntryPoints() []EntryPoint {
	return []EntryPoint{
		{Name: "generateClasses", Doc: "one file per class", Default: true, Files: l.classFiles},
		{Name: "generateIndex", Doc: "the index", Files: l.indexFiles},
	}
}
func (fakeLanguage) Templates() fs.FS {
	return fstest.MapFS{"class.tmpl": &fstest.MapFile{Data: []byte(`{{ define "class" -}}
class {{ .Name }} {
	{{ .Greeting }}
	// Start of user code {{ .Name }}
	// End of user code
}
{{- end }}
`)}}
}
func (fakeLanguage) Funcs() template.FuncMap { return nil }
func (fakeLanguage) Regions() *writer.RegionSyntax {
	return &writer.RegionSyntax{Start: "// Start of user code %s", End: "// End of user code"}
}
func (fakeLanguage) Formatter() writer.Formatter { return nil }
func (fakeLanguage) NameStyle() naming.Style     { return naming.Regex }

func (fakeLanguage) classFiles(ctx *Context, pkg ecore.EPackage) ([]File, error) {
	var files []File
	for _, class := range ctx.Model.Package(pkg).Classes {
		data := map[string]string{"Name": class.GetName(), "Greeting": ctx.Props.Get("greeting")}
		files = append(files, File{Path: pkg.GetName() + "/" + class.GetName() + ".txt", Body: Templated("class", data), Header: true, Protected: true})
	}
	return files, nil
}

func (fakeLanguage) indexFiles(ctx *Context, pkg ecore.EPackage) ([]File, error) {
	return []File{{Path: "index.txt", Body: Bytes([]byte("index\n"))}}, nil
}

const shopModel = "../../testdata/models/shop.ecore"

func TestValidateFakeLanguage(t *testing.T) {
	require.NoError(t, Validate(fakeLanguage{}))
}

func TestRunEndToEnd(t *testing.T) {
	dir := t.TempDir()
	var out, errOut bytes.Buffer
	req := Request{
		Lang: fakeLanguage{}, ModelPath: shopModel, OutDir: dir,
		Version: "v1.2.3",
		Props:   map[string]string{"greeting": "bonjour", "unknownKey": "x"},
		Output:  &out, ErrOutput: &errOut,
	}
	report, err := Run(context.Background(), req)
	require.NoError(t, err)
	assert.Equal(t, len(report.Files), report.Count(writer.Written))
	assert.Contains(t, out.String(), "file generated: ")
	assert.Contains(t, errOut.String(), `property "unknownKey" is not known`)

	content, err := os.ReadFile(filepath.Join(dir, "shop", "Product.txt"))
	require.NoError(t, err)
	assert.Equal(t, "// Code generated by soft-gen fake. DO NOT EDIT.\n\n\nclass Product {\n\tbonjour\n\t// Start of user code Product\n\t// End of user code\n}\n", string(content))
	assert.NoFileExists(t, filepath.Join(dir, "index.txt"), "generateIndex is not a default template")
	assert.NoFileExists(t, filepath.Join(dir, ManifestName), "no file generated in the output folder itself")
	manifest, err := os.ReadFile(filepath.Join(dir, "shop", ManifestName))
	require.NoError(t, err)
	assert.Equal(t, "# Code generated by soft-gen fake. DO NOT EDIT.\ngenerator: soft-gen fake\nversion: v1.2.3\npackage: http://soft.gen/test/shop\n", string(manifest))

	// a user edits the region, the next run keeps it
	edited := bytes.Replace(content, []byte("// Start of user code Product\n"), []byte("// Start of user code Product\n\tmine\n"), 1)
	require.NoError(t, os.WriteFile(filepath.Join(dir, "shop", "Product.txt"), edited, 0o644))
	req.EntryPoints = []string{"generateClasses", "generateIndex"}
	req.Silent = true
	_, err = Run(context.Background(), req)
	require.NoError(t, err)
	content, _ = os.ReadFile(filepath.Join(dir, "shop", "Product.txt"))
	assert.Contains(t, string(content), "// Start of user code Product\n\tmine\n\t// End of user code")
	assert.FileExists(t, filepath.Join(dir, "index.txt"))
	assert.FileExists(t, filepath.Join(dir, ManifestName), "index.txt is generated in the output folder")
}

func TestRunDiffAndDryRun(t *testing.T) {
	dir := t.TempDir()
	var out bytes.Buffer
	req := Request{Lang: fakeLanguage{}, ModelPath: shopModel, OutDir: dir, Output: &out, ErrOutput: &out, Diff: true}
	report, err := Run(context.Background(), req)
	require.NoError(t, err)
	assert.Equal(t, len(report.Files), report.Count(writer.Different), "nothing exists yet: everything differs")
	assert.NoFileExists(t, filepath.Join(dir, "shop", "Product.txt"))

	req.Diff, req.DryRun = false, true
	report, err = Run(context.Background(), req)
	require.NoError(t, err)
	assert.Equal(t, len(report.Files), report.Count(writer.Skipped))
	assert.NoFileExists(t, filepath.Join(dir, "shop", "Product.txt"))
}

func TestRunErrors(t *testing.T) {
	var out bytes.Buffer
	_, err := Run(context.Background(), Request{Lang: fakeLanguage{}, ModelPath: "missing.ecore", OutDir: t.TempDir(), Output: &out, ErrOutput: &out})
	assert.Error(t, err)
	_, err = Run(context.Background(), Request{Lang: fakeLanguage{}, ModelPath: shopModel, OutDir: t.TempDir(), EntryPoints: []string{"nope"}, Output: &out, ErrOutput: &out})
	assert.ErrorContains(t, err, `unknown template "nope"`)
	_, err = Run(context.Background(), Request{})
	assert.Error(t, err)
}

func TestRegistry(t *testing.T) {
	Register(fakeLanguage{})
	lang, ok := Lookup("fake")
	assert.True(t, ok)
	assert.Equal(t, "soft-gen fake", GeneratorOf(lang))
	_, ok = Lookup("none")
	assert.False(t, ok)
	assert.NotEmpty(t, Languages())
	assert.Panics(t, func() { Register(fakeLanguage{}) })
}
